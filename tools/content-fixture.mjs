#!/usr/bin/env node
// Writes src/editor/fixture/content.json, the mock backend's copy of the content tree (/editor/?mock):
// every schema, two whole worlds (LEGO Center 1200, Isle of Yarr 4200), what they name, a few
// records of every other kind, and the achievements the mock's smash achievements name.
//   node tools/content-fixture.mjs [path/to/lmoxide/content]
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, relative, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const tree = process.argv[2] ?? join(here, '../../lmoxide/content')
const out = join(here, '../src/editor/fixture/content.json')

const files = []
const walk = (d) => {
  for (const n of readdirSync(d)) {
    if (n.startsWith('.')) continue
    const p = join(d, n)
    if (statSync(p).isDirectory()) walk(p)
    else if (n.endsWith('.json')) files.push(p)
  }
}
walk(tree)
const read = (p) => JSON.parse(readFileSync(p, 'utf8'))

const schemas = {}
let index = null
const records = new Map() // id -> { record, file }
for (const f of files) {
  const rel = relative(tree, f)
  if (rel.startsWith('schemas/')) {
    if (rel === 'schemas/index.json') index = read(f)
    else schemas[rel.slice(8).replace('.schema.json', '')] = read(f)
    continue
  }
  if (['content.json', 'tunables.json', 'texts.json'].includes(rel)) continue
  const v = read(f)
  const list = v.id ? [v] : Object.values(v).flat()
  for (const r of list) records.set(`${r.id}@${r.feature ?? 'live'}`, { record: r, file: rel })
}

const keep = new Set()
const byId = (id) => [...records.keys()].filter((k) => k.startsWith(`${id}@`))
const want = (id) => {
  for (const k of byId(id)) {
    if (keep.has(k)) continue
    keep.add(k)
    // what it names, one level down for templates (skills, loot, factions ...)
    JSON.stringify(records.get(k).record, (key, val) => {
      if (typeof val === 'string' && /^(npc|object|loot|skill|buff|faction|dialogue|item|region|minifig)\//.test(val) && !keep.has(`${val}@live`)) want(val)
      return val
    })
  }
}
for (const [k, { file }] of records) if (/^worlds\/(1200|4200)-/.test(file)) want(k.split('@')[0])
const kinds = index.kinds.map((k) => k.kind)
for (const kind of kinds) {
  const ids = [...records.keys()].filter((k) => k.startsWith(`${kind}/`) && !/^\w+\/\d+\//.test(k))
  for (const k of ids.slice(0, 25)) want(k.split('@')[0])
}
for (const id of ['achievement/judge-the-witch-hunter', 'achievement/cyclops-the-witch-hunter', 'achievement/judge', 'achievement/cyclops', 'minifig/judge', 'minifig/cyclops']) want(id)

const texts = read(join(tree, 'texts.json'))
const usedTexts = new Set()
for (const k of keep) for (const t of records.get(k).record.texts ?? []) usedTexts.add(String(t))
const pick = (o, keys) => Object.fromEntries(Object.entries(o).filter(([k]) => keys.has(k)))

mkdirSync(dirname(out), { recursive: true })
const data = {
  _comment: 'Generated by tools/content-fixture.mjs from lmoxide/content: the mock backend\'s content tree.',
  index,
  schemas,
  records: [...keep].sort().map((k) => records.get(k)),
  texts: { texts: pick(texts.texts, usedTexts), names: texts.names },
}
writeFileSync(out, JSON.stringify(data))
console.log(`${data.records.length} records, ${(JSON.stringify(data).length / 1024).toFixed(0)} KiB -> ${relative(process.cwd(), out)}`)
